// ---- behaviour in headless Chrome ----
const { findChrome } = require("../tools/cdp.js");
const chrome = findChrome();
const { launch, openUI } = require("../tools/ui-harness.js");

test("UI states, layout and wiring (headless Chrome)", { skip: chrome ? false : "no Chrome/Chromium" }, async (t) => {
  const browser = await launch(chrome);
  t.after(() => browser.close());
  const page = await openUI(browser, { width: 469, height: 650, connected: true });
  const ev = (js) => page.eval(js);
  const state = () => ev("document.getElementById('app').dataset.state");
  const posted = () => ev("window.__posted");
  const wait = (ms) => ev(`new Promise(r => setTimeout(r, ${ms}))`);
  await ev("__ub.ui.throttleMs = 0; true"); // the throttle has its own test below

  await t.test("starts in Waiting, asks for init and the compact size", async () => {
    assert.strictEqual(await state(), "waiting");
    const p = await posted();
    assert.ok(p.some((m) => m.type === "init"));
    assert.ok(p.some((m) => m.type === "resize" && m.width === 460 && m.height === 460));
    assert.strictEqual(await ev("document.getElementById('resultTitle').textContent"), "Choose Frame or Layer");
  });

  await t.test("connection badge follows /ping", async () => {
    await wait(50);
    assert.strictEqual(await ev("document.getElementById('statusText').textContent"), "Connected");
    await ev("window.__bridge.connected = false; document.getElementById('status').click(); true"); await wait(50);
    assert.strictEqual(await ev("document.getElementById('statusText').textContent"), "AE Disconnected");
    assert.match(await ev("getComputedStyle(document.getElementById('statusText')).color"), /255, 51, 71/);
    await ev("window.__bridge.connected = true; document.getElementById('status').click(); true"); await wait(50);
    assert.match(await ev("getComputedStyle(document.getElementById('statusText')).color"), /50, 179, 50/);
  });

  await t.test("selection -> Ready with the design layout", async () => {
    await ev("__toUI({type:'options',options:{rasterScaleCap:2,groupsAs:'parent',compMode:'active'}}); __toUI({type:'selection',count:2,names:['Hero','Card'],changed:true}); true");
    assert.strictEqual(await state(), "ready");
    assert.ok((await posted()).some((m) => m.type === "resize" && m.width === 469 && m.height === 650));
    assert.strictEqual(await ev("document.getElementById('frameName').textContent"), "Hero  +1");
    assert.deepStrictEqual(await ev("['capValue','groupsAsValue','compModeValue'].map(i => document.getElementById(i).textContent)"), ["2x", "Parented nulls", "Into active comp"]);
    const h = await ev("['.head','.stage','.actions','.options','.foot'].map(s => Math.round(document.querySelector(s).getBoundingClientRect().height))");
    assert.deepStrictEqual(h, [65, 323, 81, 113, 68], "section heights from the Figma frame");
    const app = await ev("(() => { const r = document.getElementById('app').getBoundingClientRect(); return [r.width, r.height]; })()");
    assert.deepStrictEqual(app, [469, 650]);
    assert.strictEqual(await ev("Math.round(document.querySelector('.field.scale').getBoundingClientRect().width)"), 85);
    assert.strictEqual(await ev("getComputedStyle(document.body).fontFamily.split(',')[0].replace(/\"/g,'')"), "Plus Jakarta Sans");
  });

  await t.test("options are saved", async () => {
    await ev("const s = document.getElementById('cap'); s.value = '4'; s.dispatchEvent(new Event('change')); true");
    const last = (await posted()).filter((m) => m.type === "save-options").pop();
    assert.deepStrictEqual(last.options, { rasterScaleCap: 4, groupsAs: "parent", compMode: "active" });
    assert.strictEqual(await ev("document.getElementById('capValue').textContent"), "4x");
  });

  await t.test("scale field opens the DS dropdown menu (1x-4x, checkmark on the current value)", async () => {
    await ev("document.querySelector('.field.scale').click(); true"); await wait(220); // let the open animation finish
    const m = await ev("(() => { const el = document.getElementById('menu'); const f = document.querySelector('.field.scale').getBoundingClientRect(); const r = el.getBoundingClientRect(); return { open: el.classList.contains('open'), items: [...el.children].map(c => c.textContent), sel: [...el.children].map(c => c.getAttribute('aria-selected')), w: Math.round(r.width), gap: Math.round(r.top - f.bottom), left: Math.round(r.left - f.left) }; })()");
    assert.deepStrictEqual(m, { open: true, items: ["1x", "2x", "3x", "4x"], sel: ["false", "false", "false", "true"], w: 85, gap: 6, left: 0 });
    await ev("document.querySelectorAll('#menu .menu-item')[1].click(); true");
    assert.strictEqual(await ev("document.getElementById('menu').classList.contains('open')"), false);
    assert.strictEqual(await ev("document.getElementById('capValue').textContent"), "2x");
    assert.strictEqual((await posted()).filter((m) => m.type === "save-options").pop().options.rasterScaleCap, 2);
    // keyboard: ArrowDown opens, ArrowDown moves, Enter picks; Escape closes
    await ev("{ const f = document.querySelector('.field[data-for=groupsAs]'); f.focus(); f.dispatchEvent(new KeyboardEvent('keydown', {key:'ArrowDown'})); } true");
    assert.strictEqual(await ev("document.getElementById('menu').classList.contains('open')"), true);
    await ev("{ const f = document.querySelector('.field[data-for=groupsAs]'); f.dispatchEvent(new KeyboardEvent('keydown', {key:'ArrowUp'})); f.dispatchEvent(new KeyboardEvent('keydown', {key:'Enter'})); } true");
    assert.strictEqual(await ev("document.getElementById('groupsAsValue').textContent"), "Precomps");
    await ev("{ const f = document.querySelector('.field[data-for=groupsAs]'); f.click(); document.body.click(); } true");
    assert.strictEqual(await ev("document.getElementById('menu').classList.contains('open')"), false, "outside click closes");
    await ev("{ const f = document.querySelector('.field[data-for=groupsAs]'); f.click(); document.querySelectorAll('#menu .menu-item')[1].click(); } true");
    assert.strictEqual(await ev("document.getElementById('groupsAsValue').textContent"), "Parented nulls");
    await ev("document.querySelector('.field.scale').click(); document.querySelectorAll('#menu .menu-item')[3].click(); true");
    assert.strictEqual(await ev("document.getElementById('capValue').textContent"), "4x");
  });

  await t.test("No bridge alert: shown while AE is unreachable, closable, back on the next disconnect", async () => {
    const alertShown = () => ev("getComputedStyle(document.querySelector('.alert-wrap')).display !== 'none'");
    const lastResize = async () => (await posted()).filter((m) => m.type === "resize").pop();
    assert.strictEqual(await alertShown(), false);
    await ev("window.__bridge.connected = false; document.getElementById('status').click(); true"); await wait(50);
    assert.strictEqual(await alertShown(), true);
    assert.deepStrictEqual(await lastResize(), { type: "resize", width: 469, height: 791 });
    assert.match(await ev("document.querySelector('.alert').textContent"), /No bridge on port 7341\.[\s\S]*Open Window > Extensions > Uiscore Bridge in After Effects\./);
    await ev("document.getElementById('alertClose').click(); true");
    assert.ok(await ev("document.getElementById('app').classList.contains('alert-leaving')"), "collapses before the window shrinks");
    assert.deepStrictEqual(await lastResize(), { type: "resize", width: 469, height: 791 }, "no resize until the collapse ends");
    await wait(250);
    assert.strictEqual(await alertShown(), false);
    assert.deepStrictEqual(await lastResize(), { type: "resize", width: 469, height: 650 });
    await ev("__ub.ping(); true"); await wait(50);
    assert.strictEqual(await alertShown(), false, "the background /ping keeps it closed while still disconnected");
    await ev("document.getElementById('status').click(); true"); await wait(50);
    assert.strictEqual(await alertShown(), true, "a click on the red badge re-checks and shows the alert again");
    await ev("document.getElementById('alertClose').click(); true"); await wait(250);
    await ev("window.__bridge.connected = true; document.getElementById('status').click(); true"); await wait(50);
    await ev("window.__bridge.connected = false; document.getElementById('status').click(); true"); await wait(50);
    assert.strictEqual(await alertShown(), true, "comes back on a new disconnect");
    await ev("window.__bridge.connected = true; document.getElementById('status').click(); true"); await wait(250);
    assert.strictEqual(await alertShown(), false);
    assert.deepStrictEqual(await lastResize(), { type: "resize", width: 469, height: 650 });
  });

  await t.test("badge click shows the check; repeated clicks are throttled and point at the alert", async () => {
    await ev("window.__bridge.connected = false; __ub.ui.throttleMs = 400; __ub.ui.lastManual = -1e9; true");
    const pings0 = await ev("window.__bridge.pings");
    await ev("document.getElementById('status').click(); true");
    assert.deepStrictEqual(await ev("[document.getElementById('status').classList.contains('checking'), document.getElementById('status').getAttribute('aria-busy')]"), [true, "true"], "visible checking indicator");
    await wait(50);
    assert.strictEqual(await ev("window.__bridge.pings"), pings0 + 1);
    await ev("document.getElementById('alertClose').click(); true"); await wait(250);
    // 2nd and 3rd click inside the window: no request, alert comes back, is focused and highlighted
    await ev("document.getElementById('status').click(); document.getElementById('status').click(); true"); await wait(30);
    assert.strictEqual(await ev("window.__bridge.pings"), pings0 + 1, "no request spam");
    assert.strictEqual(await ev("getComputedStyle(document.querySelector('.alert-wrap')).display !== 'none'"), true);
    assert.strictEqual(await ev("document.activeElement && document.activeElement.id"), "alert");
    assert.ok(await ev("document.getElementById('alert').classList.contains('attention')"));
    assert.strictEqual(await ev("getComputedStyle(document.getElementById('alert')).animationName"), "ub-shake");
    assert.strictEqual(await ev("document.getElementById('alert').getAttribute('aria-live')"), "assertive");
    // one trailing check once the throttle window is over
    await wait(500);
    assert.strictEqual(await ev("window.__bridge.pings"), pings0 + 2, "exactly one trailing check");
    await wait(900);
    assert.strictEqual(await ev("document.getElementById('alert').classList.contains('attention')"), false, "highlight fades");
    assert.strictEqual(await ev("document.getElementById('status').classList.contains('checking')"), false);
    // a click while a check is still running is throttled too
    await ev("__ub.ui.throttleMs = 0; __ub.ui.checking = true; document.getElementById('status').click(); __ub.ui.checking = false; true");
    assert.strictEqual(await ev("window.__bridge.pings"), pings0 + 2);
    await ev("window.__bridge.connected = true; document.getElementById('status').click(); true"); await wait(250);
    assert.strictEqual(await ev("document.getElementById('statusText').textContent"), "Connected");
  });

  await t.test("Mark as raster posts mark-raster", async () => {
    await ev("document.getElementById('mark').click(); true");
    assert.ok((await posted()).some((m) => m.type === "mark-raster"));
  });

  await t.test("Export -> Exporting -> upload -> Done", async () => {
    await ev("document.getElementById('send').click(); true");
    assert.strictEqual(await state(), "exporting");
    assert.ok(await ev("getComputedStyle(document.querySelector('.loading')).display !== 'none'"));
    const exp = (await posted()).filter((m) => m.type === "export").pop();
    assert.strictEqual(exp.options.rasterScaleCap, 4);
    await ev("document.getElementById('send').click(); true");
    assert.strictEqual((await posted()).filter((m) => m.type === "export").length, 1, "no double export while busy");
    await ev("__toUI({type:'selection',count:0,names:[],changed:true}); true");
    assert.strictEqual(await state(), "exporting", "selection changes do not interrupt an export");
    await ev("__toUI({type:'selection',count:2,names:['Hero','Card'],changed:true}); true");
    await ev("__toUI({type:'job', job:{comps:[{}], warnings:[{name:'Blur',message:'approximated'}]}, images:[{id:'img1', bytes:[1,2,3]}]}); true");
    await wait(80);
    assert.strictEqual(await state(), "success");
    const body = JSON.parse((await ev("window.__bridge.imports"))[0]);
    assert.deepStrictEqual(body.images, { img1: "AQID" });
    assert.ok((await posted()).some((m) => m.type === "notify" && /Sent to After Effects: 1 comp, 12 layers/.test(m.text)));
    assert.ok((await posted()).some((m) => m.type === "resize" && m.width === 460));
  });

  await t.test("Try again re-exports; failures show the Error state", async () => {
    await ev("window.__bridge.importResponse = { ok: false, error: 'No active comp' }; document.getElementById('retry').click(); true");
    assert.strictEqual(await state(), "exporting");
    await ev("__toUI({type:'job', job:{comps:[{}]}, images:[]}); true"); await wait(80);
    assert.strictEqual(await state(), "error");
    assert.match(await ev("document.getElementById('resultDesc').textContent"), /No active comp/);
    await ev("__toUI({type:'selection',count:1,names:['Other'],changed:true}); true");
    assert.strictEqual(await state(), "ready", "a new selection leaves Done/Error");
    await ev("document.getElementById('send').click(); __toUI({type:'export-error', text:'Select one or more frames first.\\n at x'}); true");
    assert.strictEqual(await state(), "error");
    assert.strictEqual(await ev("document.getElementById('resultDesc').textContent"), "Select one or more frames first.");
  });

  await t.test("bridge offline during upload -> Error, no crash", async () => {
    await ev("window.__bridge.connected = false; __ub.setConnected(false); __ub.setState('exporting'); __toUI({type:'job', job:{comps:[{}]}, images:[]}); true");
    await wait(1700);
    assert.strictEqual(await state(), "error");
    assert.match(await ev("document.getElementById('resultDesc').textContent"), /not reachable/);
  });

  await t.test("empty selection -> Waiting; no visible log panel", async () => {
    await ev("__toUI({type:'selection',count:0,names:[],changed:true}); true");
    assert.strictEqual(await state(), "waiting");
    assert.strictEqual(await ev("document.getElementById('log')"), null);
    await ev("document.getElementById('version').click(); true");
    assert.strictEqual(await state(), "waiting");
  });
});

test("dark / light theme: Figma classes, prefers-color-scheme fallback, dark assets, reduced motion (headless Chrome)", { skip: chrome ? false : "no Chrome/Chromium" }, async (t) => {
  const browser = await launch(chrome);
  t.after(() => browser.close());
  const bg = (page) => page.eval("getComputedStyle(document.querySelector('.foot')).backgroundColor");
  const card = (page) => page.eval("getComputedStyle(document.querySelector('.result')).backgroundColor");

  await t.test("follows html.figma-dark / html.figma-light and switches live", async () => {
    const page = await openUI(browser, { width: 469, height: 650 });
    assert.strictEqual(await bg(page), "rgb(244, 244, 245)", "light by default");
    await page.eval("document.documentElement.classList.add('figma-dark'); true");
    assert.strictEqual(await bg(page), "rgb(39, 39, 42)");
    assert.strictEqual(await card(page), "rgb(24, 24, 27)");
    assert.strictEqual(await page.eval("getComputedStyle(document.querySelector('.result-text .title')).color"), "rgb(244, 244, 245)");
    assert.strictEqual(await page.eval("getComputedStyle(document.querySelector('.result-text .desc')).color"), "rgb(159, 159, 169)");
    await page.eval("__ub.setState('exporting'); true");
    assert.deepStrictEqual(await page.eval("[...document.querySelectorAll('.loading-row img')].map(i => getComputedStyle(i).display)"), ["none", "block"], "dark loading asset");
    await page.eval("document.documentElement.classList.replace('figma-dark', 'figma-light'); true");
    assert.strictEqual(await bg(page), "rgb(244, 244, 245)");
    assert.deepStrictEqual(await page.eval("[...document.querySelectorAll('.loading-row img')].map(i => getComputedStyle(i).display)"), ["block", "none"]);
    await page.close();
  });

  await t.test("prefers-color-scheme: dark is the fallback; a Figma class wins", async () => {
    const page = await openUI(browser, { width: 469, height: 650, colorScheme: "dark" });
    assert.strictEqual(await bg(page), "rgb(39, 39, 42)");
    await page.eval("document.documentElement.classList.add('figma-light'); true");
    assert.strictEqual(await bg(page), "rgb(244, 244, 245)");
    await page.close();
  });

  await t.test("dark + prefers-reduced-motion: alert attention is a highlight without the shake", async () => {
    const page = await openUI(browser, { width: 469, height: 650, theme: "dark", reducedMotion: true });
    await page.eval("__ub.ui.throttleMs = 3000; window.__bridge.connected = false; document.getElementById('status').click(); true");
    await page.eval("new Promise(r => setTimeout(r, 50))");
    await page.eval("document.getElementById('alertClose').click(); true");
    assert.strictEqual(await page.eval("getComputedStyle(document.querySelector('.alert-wrap')).display"), "none", "no collapse delay with reduced motion");
    await page.eval("document.getElementById('status').click(); true");
    assert.strictEqual(await page.eval("document.activeElement.id"), "alert");
    assert.strictEqual(await page.eval("getComputedStyle(document.getElementById('alert')).animationName"), "none");
    assert.strictEqual(await page.eval("getComputedStyle(document.getElementById('alert')).outlineColor"), "rgb(255, 51, 71)");
    assert.strictEqual(await page.eval("getComputedStyle(document.getElementById('alert')).backgroundColor"), "rgb(75, 4, 11)");
    await page.close();
  });
});
