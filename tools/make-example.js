#!/usr/bin/env node
/*
 * Generates examples/ from the test fixture by running the real pipeline:
 *   Figma stub -> serializer -> payload -> HTTP bridge (random port) -> job folder -> builder.jsx in the AE mock.
 * Outputs:
 *   examples/sample-job.json          job JSON as the Figma plugin sends it (images stripped)
 *   examples/sample-payload.json      full POST /import body (job + base64 PNGs)
 *   ae-extension/examples/sample-payload.json  same, bundled for the panel's "Import sample job" button
 *   examples/sample-import-result.json what the builder reported + resulting layer tree (mock AE)
 */
const fs = require("fs");
const os = require("os");
const path = require("path");
const G = require("../shared/geom.js");
const { createUBSerializer } = require("../figma-plugin/src/serializer.js");
const { createBridge } = require("../ae-extension/js/server.js");
const S = require("../tests/helpers/figma-stub.js");
const F = require("../tests/helpers/fixture.js");
const { createAE, describe } = require("../tests/helpers/ae-mock.js");

const ROOT = path.join(__dirname, "..");
(async () => {
  const { job, images } = await createUBSerializer(S.figmaApi, G, {}).serialize([F.buildCard()], { jobId: "sample-card", source: { file: "Example.fig", page: "Page 1" } });
  job.createdAt = "2026-11-05T12:00:00.000Z";
  const payload = { job, images: {} };
  images.forEach((i) => { payload.images[i.id] = Buffer.from(i.bytes).toString("base64"); });
  fs.mkdirSync(path.join(ROOT, "examples"), { recursive: true });
  fs.mkdirSync(path.join(ROOT, "ae-extension", "examples"), { recursive: true });
  fs.writeFileSync(path.join(ROOT, "examples", "sample-job.json"), JSON.stringify(job, null, 2));
  fs.writeFileSync(path.join(ROOT, "examples", "sample-payload.json"), JSON.stringify(payload));
  fs.writeFileSync(path.join(ROOT, "ae-extension", "examples", "sample-payload.json"), JSON.stringify(payload));

  const jobsRoot = fs.mkdtempSync(path.join(os.tmpdir(), "ub-example-"));
  let ae;
  const bridge = createBridge({
    geom: G, templatesDir: path.join(ROOT, "ae-extension", "assets", "gradient-templates"), getAeVersion: () => "26.3",
    resolveJobsRoot: async () => jobsRoot,
    evalScript: async (script) => { ae = createAE({ characterRange: true }); return ae.run(script); }
  });
  const port = await bridge.start(0);
  const res = await (await fetch(`http://127.0.0.1:${port}/import`, { method: "POST", headers: { "Content-Type": "text/plain" }, body: JSON.stringify(payload) })).json();
  await bridge.stop();
  const main = ae.items.find((i) => i instanceof ae.CompItem && i.name === job.comps[0].name);
  const files = [];
  const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).forEach((e) => e.isDirectory() ? walk(path.join(d, e.name)) : files.push(path.relative(res.jobDir, path.join(d, e.name)).replace(/\\/g, "/")));
  walk(res.jobDir);
  const out = { note: "Generated by tools/make-example.js with the AE object-model MOCK (not real After Effects).", result: Object.assign({}, res, { jobDir: "<jobs root>/" + path.basename(res.jobDir), jobFile: undefined }), jobFolderFiles: files.sort(), layers: describe(main), presetsApplied: ae.log.presets.map((p) => ({ layer: p.layer, file: path.basename(p.file) })) };
  fs.writeFileSync(path.join(ROOT, "examples", "sample-import-result.json"), JSON.stringify(out, null, 2));
  console.log("ok:", res.ok, res.summary);
  console.log("job folder:", files.join(", "));
})().catch((e) => { console.error(e); process.exit(1); });
