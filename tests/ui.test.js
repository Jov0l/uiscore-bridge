/* Figma plugin UI (figma-plugin/ui.html, built from figma-plugin/src/ui.html).
 * Static checks always run; the behaviour checks drive the real UI in headless Chrome (skipped without Chrome). */
const test = require("node:test");
const assert = require("node:assert");
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const ui = read("figma-plugin/ui.html");
const src = read("figma-plugin/src/ui.html");

test("ui.html is built from src/ui.html with every asset inlined", () => {
  assert.match(ui, /GENERATED by scripts\/build\.js/);
  assert.doesNotMatch(ui, /\{\{(asset|version)/);
  for (const m of src.matchAll(/\{\{asset:([\w.-]+)\}\}/g)) assert.ok(fs.existsSync(path.join(ROOT, "figma-plugin/assets", m[1])), m[1]);
  assert.doesNotMatch(ui, /figma\.com\/api\/mcp\/asset|localhost:3845/, "no temporary Figma MCP asset URLs");
  const pkg = JSON.parse(read("package.json"));
  assert.ok(ui.includes("Uiscore Bridge - v" + pkg.version));
});

test("ui uses the design font (Plus Jakarta Sans) and never Manrope", () => {
  for (const f of ["figma-plugin/ui.html", "figma-plugin/src/ui.html", "ae-extension/css/panel.css", "ae-extension/index.html"]) assert.doesNotMatch(read(f), /manrope/i, f);
  assert.match(ui, /--font-family-body:\s*"Plus Jakarta Sans", Inter/);
  assert.match(ui, /fonts\.googleapis\.com\/css2\?family=Plus\+Jakarta\+Sans:wght@400;500/);
});

test("Core DS tokens are CSS variables with DS naming", () => {
  const tokens = { "--backround-default-bg": "#ffffff", "--backround-default-bg-hover": "#f4f4f5", "--border-default-border-default": "#e4e4e7",
    "--text-default-txt-default": "#09090b", "--text-default-txt-subtle": "#52525c", "--text-default-txt-muted": "#71717b",
    "--text-error-text-default": "#ff3347", "--text-success-text-default": "#32b332", "--button-neutral-button-hover": "#f4f4f5" };
  for (const [k, v] of Object.entries(tokens)) assert.ok(ui.includes(k + ": " + v), k);
  for (const k of ["--spacing-24", "--radius-6", "--radius-full", "--font-size-medium", "--button-transparrent-button"]) assert.ok(ui.includes(k + ":"), k);
});

test("manifest network access: localhost bridge + Google Fonts only, valid URLs", () => {
  const m = JSON.parse(read("figma-plugin/manifest.json"));
  assert.deepStrictEqual(m.networkAccess.allowedDomains, ["http://localhost:7341", "https://fonts.googleapis.com", "https://fonts.gstatic.com"]);
  assert.ok(m.networkAccess.devAllowedDomains.includes("http://localhost:7341"));
  for (const d of m.networkAccess.allowedDomains.concat(m.networkAccess.devAllowedDomains)) {
    const u = new URL(d);
    assert.ok(!/^\d+\.\d+\.\d+\.\d+$/.test(u.hostname) && !u.hostname.includes(":"), "no IP literals: " + d);
  }
  assert.match(ui, /var HOSTS = \["http:\/\/localhost:" \+ PORT\];/);
});

test("main.js opens the UI at the design size and handles resize", () => {
  const main = read("figma-plugin/src/main.js");
  const calls = [];
  const figma = {
    showUI: (html, o) => calls.push(["showUI", o]), on() {}, notify() {}, root: { name: "f" },
    currentPage: { selection: [], name: "p" }, clientStorage: { getAsync: async () => null, setAsync: async () => {} },
    ui: { postMessage: (m) => calls.push(["post", m]), resize: (w, h) => calls.push(["resize", w, h]), onmessage: null }
  };
  vm.runInNewContext(main + "\nthis.figma = figma;", { figma, __html__: "", setTimeout, createUBSerializer() {}, UBGeom: {} });
  assert.strictEqual(calls[0][1].themeColors, true, "Figma puts figma-dark / figma-light on <html>");
  assert.deepStrictEqual(calls[0][1].width, 460); assert.deepStrictEqual(calls[0][1].height, 460);
  figma.ui.onmessage({ type: "resize", width: 469, height: 650 });
  assert.deepStrictEqual(calls.find((c) => c[0] === "resize"), ["resize", 469, 650]);
});

